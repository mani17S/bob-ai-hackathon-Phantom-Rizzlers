/**
 * Shared domain types. Keep these aligned with the backend's response
 * schemas (docs/architecture.md) - they are the API contract on the client.
 */

/* --- Domain enums --------------------------------------------------------- */

export type Severity = "critical" | "high" | "medium" | "low";

export type PipelineStatus = "healthy" | "failing" | "idle";

export type Trend = "positive" | "negative" | "neutral";

/* --- Domain entities -------------------------------------------------------- */

/** Filter params for the anomaly list endpoint. */
export interface AnomalyQuery {
  /** Full-text search over pipeline name, anomaly ID, and summary. */
  query?: string;
  severity?: Severity | "all";
}

export interface Anomaly {
  id: string;
  pipeline: string;
  severity: Severity;
  /** Human-readable one-liner generated by the model. */
  summary: string;
  /** Model score between 0 and 1. */
  score: number;
  detectedAt: string; // ISO 8601
}

export interface Pipeline {
  id: string;
  name: string;
  status: PipelineStatus;
  lastRunAt: string; // ISO 8601
  /** Success rate 0-1, e.g. 0.82 → 82%. */
  successRate: number;
}

export interface DashboardSummary {
  anomalies24h: number;
  openIncidents: number;
  pipelinesMonitored: number;
  /** Composite health 0-100. */
  healthScore: number;
}

/* --- API response envelopes -------------------------------------------------- */

export interface OverviewResponse {
  summary: DashboardSummary;
  anomalies: Anomaly[];
  pipelines: Pipeline[];
}

/** Generic pagination envelope for future list endpoints. */
export interface Paginated<T> {
  items: T[];
  total: number;
  page: number;
  pageSize: number;
}
